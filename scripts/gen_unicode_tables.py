"""Generate src/unicode_tables.h: code-point ranges for the Unicode classes the
tokenizer's pre-split regex uses: \\p{L} (letters), \\p{N} (numbers).

Usage:
    python scripts/gen_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "unicode_tables.h"


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    body = ",\n".join(
        "    " + ", ".join(f"{{0x{a:X}, 0x{b:X}}}" for a, b in rs[i:i + 4])
        for i in range(0, len(rs), 4))
    return f"inline constexpr CodepointRange {name}[] = {{\n{body}\n}};\n"


def main() -> None:
    cat = lambda cp: unicodedata.category(chr(cp))
    letters = ranges(lambda cp: cat(cp)[0] == "L")
    numbers = ranges(lambda cp: cat(cp)[0] == "N")
    text = (
        "#pragma once\n"
        "// Generated by scripts/gen_unicode_tables.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}).\n"
        "// Do not edit by hand.\n\n"
        "#include <cstdint>\n\n"
        "namespace ie::unicode {\n\n"
        "struct CodepointRange {\n  uint32_t first, last;\n};\n\n"
        "// \\p{L}: general category L* (Lu, Ll, Lt, Lm, Lo)\n"
        + emit("kLetters", letters) +
        "\n// \\p{N}: general category N* (Nd, Nl, No)\n"
        + emit("kNumbers", numbers) +
        "\n}  // namespace ie::unicode\n")
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}: {len(letters)} letter ranges, {len(numbers)} number ranges")


if __name__ == "__main__":
    main()
